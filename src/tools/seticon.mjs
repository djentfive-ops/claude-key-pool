import * as ResEdit from 'resedit';
import * as PE from 'pe-library';
import fs from 'node:fs';
const [exePath, icoPath, version] = process.argv.slice(2);
const exe = PE.NtExecutable.from(fs.readFileSync(exePath), { ignoreCert: true });
const res = PE.NtExecutableResource.from(exe);
const iconFile = ResEdit.Data.IconFile.from(fs.readFileSync(icoPath));
const groups = ResEdit.Resource.IconGroupEntry.fromEntries(res.entries);
const gid = groups.length ? groups[0].id : 1;
const lang = groups.length ? groups[0].lang : 1033;
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries, gid, lang, iconFile.icons.map(i => i.data));
const vis = ResEdit.Resource.VersionInfo.fromEntries(res.entries);
const vi = vis[0] ?? ResEdit.Resource.VersionInfo.createEmpty();
const [a,b,c] = version.split('.').map(Number);
vi.setFileVersion(a,b,c,0,1033); vi.setProductVersion(a,b,c,0,1033);
vi.setStringValues({ lang: 1033, codepage: 1200 }, { FileDescription: 'Claude 키 묶음', ProductName: 'Claude 키 묶음', CompanyName: 'OVIS Studio', OriginalFilename: 'ClaudeKeyPool.exe', InternalName: 'ClaudeKeyPool', LegalCopyright: 'OVIS Studio' });
vi.outputToResourceEntries(res.entries);
res.outputResource(exe);
fs.writeFileSync(exePath, Buffer.from(exe.generate()));
console.log('icon+version set', gid, lang);
